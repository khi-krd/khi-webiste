type RawTrack = Omit<SoundTrack, "totalDurationSeconds" | "totalSizeBytes">;

function withTotals(track: RawTrack): SoundTrack {
	const totalDurationSeconds = track.files.reduce(
		(sum, file) => sum + (file.durationSeconds ?? 0),
		0,
	);
	const totalSizeBytes = track.files.reduce(
		(sum, file) => sum + (file.sizeBytes ?? 0),
		0,
	);
	return {
		...track,
		totalDurationSeconds:
			totalDurationSeconds > 0 ? totalDurationSeconds : null,
		totalSizeBytes: totalSizeBytes > 0 ? totalSizeBytes : null,
	};
}

